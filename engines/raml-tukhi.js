// «أحكام في علم الرمل» من كتاب «تجاربي وبرهاني في الفلك والروحاني» للطوخي (ص ١٧٩–١٩١):
// قواعدُ تُقرأ على البيوت الستّةَ عشر (١٣ الشاهد الأيمن، ١٤ الأيسر، ١٥ القاضي، ١٦ سهم القسمة).
// «أشكالُ الكوكب» = الأشكالُ المنسوبةُ إليه؛ «المتولّد من بيتين» = جمعُ شكليهما.
// ─────────────────────────────────────────────────────────────────────────────

import abjad from "./abjad.js";

const SRC = "الطوخي، تجاربي وبرهاني — أحكام في علم الرمل";
const sum = (a, b) => {
  const rows = a.rows.map((v, i) => ((v + b.rows[i]) % 2 === 0 ? 2 : 1));
  return { rows };
};
const good = (f) => f.nature === "سعد", bad = (f) => f.nature === "نحس";
const stab = (f) => (f.rows[0] === 1 && f.rows[3] === 1 ? "منقلب" : f.rows[0] === 2 && f.rows[3] === 2 ? "ثابت" : "متجسّد");
const heavy = (f) => f.rows.reduce((a, v) => a + v, 0) >= 7;
const light = (f) => f.rows.reduce((a, v) => a + v, 0) <= 5;
const of = (f, ...pl) => pl.includes(f.planet);

/** صناعاتُ الشكل في التاسع وأصدقاءُ الشكل في الحادي عشر بكوكبه [ص ١٨٤–١٨٦] */
const CRAFT_IN_9 = { "زحل": "الفلاحة والأرض", "المشتري": "الفقه والدين وطلب العلم", "المريخ": "الطبّ والبيطرة وما يُعمَل بالنار", "الشمس": "الفلك والحكمة والفلسفة", "الزهرة": "التاريخ والأخبار والفنون والألحان", "عطارد": "الحساب والكتابة وعلوم الحروف", "القمر": "خدمة الفقراء والعمل الصالح", "العقدة الصاعدة": "النظر في الأديان والمذاهب، برأيٍ قويٍّ مخالف", "العقدة الهابطة": "أعمالٌ لا ثباتَ فيها" };
const FRIENDS_IN_11 = { "زحل": "الفلّاحون وأهل الأرض", "المشتري": "القضاة والعلماء", "المريخ": "الحدّادون والجنود وأصحاب الصنعة", "الزهرة": "النساء والشباب", "عطارد": "الكتّاب والمحاسبون", "القمر": "أرباب الحِرَف", "العقدة الصاعدة": "أهل الفلسفة والجدل", "العقدة الهابطة": "من لا يُؤتمَن: مقامرٌ أو كذّاب" };

const TOPICS = [
  ["pregnancy", ["حمل", "حامل", "ولادة", "اولد", "انجب", "ولد"]],
  ["illness", ["مرض", "اشفى", "شفاء", "مريض", "علة", "وجع"]],
  ["marriage", ["زواج", "اتزوج", "نكاح", "خطبة", "عروس", "عريس"]],
  ["court", ["قضية", "محكمة", "دعوى", "خصومة"]],
  ["post", ["وظيفة", "منصب", "ولاية", "ترقية", "تعيين"]],
  ["craft", ["مهنة", "صنعة", "تخصص", "دراسة", "علم"]],
  ["friend", ["صديق", "شريك", "شراكة"]],
  ["enemy", ["عدو", "اعداء", "حاسد"]],
  ["prison", ["سجن", "محبوس", "مسجون", "حبس"]],
  ["debt", ["قرض", "دين", "سلفة", "يرد"]],
  ["absent", ["غائب", "مسافر", "يرجع", "مفقود"]],
  ["love", ["حب", "يحبني", "تحبني", "محبة"]],
];
export function topicOf(question) {
  const q = abjad.normalize(String(question || ""));
  for (const [t, kws] of TOPICS) if (kws.some((k) => q.includes(abjad.normalize(k)))) return t;
  return "general";
}

/**
 * @param {object} chart  نتيجةُ raml.chart (فيها taskin16)
 * @param {string} question
 * @param {(rows:number[])=>object} byRows  دالّةُ إيجاد الشكل من صفوفه
 * @returns {{topic:string, details:{text:string,s:number,page:number}[], score:number, src:string}}
 */
export function judge(chart, question, byRows) {
  const H = (n) => chart.taskin16[n - 1].figure;
  const gen = (a, b) => byRows(sum(H(a), H(b)).rows);
  const gen2 = (f1, f2) => byRows(sum(f1, f2).rows);
  const out = [];
  const add = (text, s, page) => out.push({ text, s, page });
  const topic = topicOf(question);
  const same = (a, b) => H(a).rows.join("") === H(b).rows.join("");
  const repeatsIn = (n, list) => list.some((m) => same(n, m));

  if (topic === "pregnancy") {
    add(good(H(1)) ? "الأمُّ تسلم." : bad(H(1)) ? "يُخشى على الأمّ؛ المتابعةُ الطبّيّة ضروريّة." : "حالُ الأمّ وسط.", good(H(1)) ? 0.5 : bad(H(1)) ? -0.5 : 0, 182);
    if (bad(H(6)) || bad(H(8))) add("نحسٌ في السادس أو الثامن: يُخشى على الجنين.", -0.5, 182);
    if (["الشمس", "المريخ", "زحل", "المشتري"].includes(H(5).planet)) add("الشكلُ في الخامس مذكّر: الأرجحُ ذكر.", 0, 182);
    else add("الشكلُ في الخامس مؤنّث: الأرجحُ أنثى.", 0, 182);
    add(stab(H(5)) === "منقلب" ? "الولادةُ سهلة." : stab(H(5)) === "ثابت" ? "الولادةُ متعسّرة." : "الولادةُ متوسّطة.", stab(H(5)) === "منقلب" ? 0.3 : stab(H(5)) === "ثابت" ? -0.3 : 0, 182);
    if (stab(H(1)) === "متجسّد" && stab(H(15)) === "متجسّد") add("الأوّلُ والخامسَ عشر متجسّدان: احتمالُ توأم.", 0, 182);
    if (good(H(6))) add("سعدٌ في السادس: يكون المولودُ ذا مال.", 0.2, 182);
  } else if (topic === "illness") {
    if (same(1, 6)) add("الأوّلُ تكرّر في السادس: المرضُ يطول.", -0.4, 182);
    if (same(1, 8)) add("الأوّلُ تكرّر في الثامن: مرضٌ ثقيل.", -0.6, 182);
    if (good(H(1)) && good(H(15))) add("الأوّلُ والخامسَ عشر سعود: يبرأ.", 0.6, 182);
    else if (bad(H(1)) && bad(H(15))) add("الأوّلُ والخامسَ عشر نحوس: يطولُ المرض.", -0.5, 182);
    const el = { "نار": "صفراء (حرارة)", "هواء": "دمويّة ورياح", "ماء": "برودةٌ ورطوبة", "تراب": "سوداءُ ويبس" }[H(1).element];
    if (el) add(`طبعُ العلّة: ${el}.`, 0, 183);
    if (bad(H(8))) add("نحسٌ في الثامن: انتبهْ للبصر.", 0, 182);
    if (good(H(9))) add("سعدٌ في التاسع: البصرُ سليم.", 0, 182);
    if (of(H(6), "زحل") || of(H(8), "زحل")) add("أشكالُ زحل في السادس أو الثامن: ثقلٌ في السمع.", 0, 182);
  } else if (topic === "marriage") {
    if ([1, 5, 7].some((n) => of(H(n), "الزهرة", "المشتري"))) add("أشكالُ الزهرة أو المشتري في الأوّل أو الخامس أو السابع: يتمُّ الزواج.", 0.6, 183);
    if (good(H(8))) add("سعدٌ في الثامن: فرحُها عالٍ.", 0.2, 183);
    add(good(H(10)) ? "الطرفُ الآخرُ من بيتٍ طيّب." : bad(H(10)) ? "انتبهْ لأصل الطرف الآخر وبيئته." : "", good(H(10)) ? 0.2 : bad(H(10)) ? -0.2 : 0, 183);
    const g = gen(1, 7);
    add(good(g) ? "تنالُ من هذا الزواج خيرًا." : bad(g) ? "في هذا الزواج تعبٌ وخلاف." : "زواجٌ جيّدٌ في عمومه.", good(g) ? 0.4 : bad(g) ? -0.4 : 0.1, 183);
    add(heavy(g) ? "الزواجُ يبطئ." : light(g) ? "الزواجُ يسرع." : "", 0, 184);
  } else if (topic === "court") {
    const g = gen(1, 7);
    add(good(g) ? "يصطلحان على ما يريده السائل." : heavy(g) ? "يدومُ الخلافُ بينهما." : "الأمرُ بينهما متردّد.", good(g) ? 0.5 : heavy(g) ? -0.4 : 0, 184);
    if (of(H(1), "الشمس")) add("أشكالُ الشمس في الأوّل: يقفان أمام صاحب سلطان.", 0, 184);
    if (of(H(10), "المشتري")) add("أشكالُ المشتري في العاشر: يقفان أمام القاضي.", 0, 184);
    if (of(H(10), "المريخ")) add("أشكالُ المريخ في العاشر: يقفان أمام الوالي.", 0, 184);
    add(good(H(8)) ? "سعدٌ في الثامن: الظفرُ للسائل." : bad(H(8)) ? "نحسٌ في الثامن: الظفرُ للخصم." : "", good(H(8)) ? 0.5 : bad(H(8)) ? -0.5 : 0, 184);
  } else if (topic === "post") {
    const s1 = stab(H(1)), s10 = stab(H(10));
    add(s1 === "ثابت" && s10 === "ثابت" ? "الأوّلُ والعاشرُ ثابتان: المنصبُ يدوم." : s1 === "منقلب" && s10 === "منقلب" ? "الأوّلُ والعاشرُ منقلبان: لا يدومُ طويلًا." : "يدومُ مدّةً ثمّ يتبدّل.", s1 === "ثابت" && s10 === "ثابت" ? 0.4 : s1 === "منقلب" && s10 === "منقلب" ? -0.4 : 0, 185);
    const g = gen(1, 10);
    add(of(g, "الشمس", "القمر", "المشتري", "الزهرة") ? "المتولّدُ من الأوّل والعاشر سعيد: تتمُّ وتستمرّ." : "المتولّدُ من الأوّل والعاشر لا يساعد: لا تتمُّ الآن.", of(g, "الشمس", "القمر", "المشتري", "الزهرة") ? 0.5 : -0.4, 185);
  } else if (topic === "craft") {
    add(`ما يناسبُك من العلوم والصنائع: ${CRAFT_IN_9[H(9).planet] || "—"}.`, 0, 184);
    add(good(H(15)) && good(H(11)) ? "صنعتُك قليلةُ التعب." : bad(H(15)) && bad(H(11)) ? "صنعتُك كثيرةُ التعب." : "", 0, 184);
  } else if (topic === "friend") {
    add(good(H(1)) && good(H(11)) ? "الطرفان مخلصان، يساعدُ كلٌّ منهما الآخر." : bad(H(1)) && bad(H(11)) ? "يُخشى أن يخونَ أحدُهما الآخر." : "علاقةٌ متوسّطة.", good(H(1)) && good(H(11)) ? 0.5 : bad(H(1)) && bad(H(11)) ? -0.5 : 0, 185);
    const g = gen(1, 11);
    add(good(g) ? "المتولّدُ منهما سعيد: صحبةٌ نافعة." : bad(g) ? "المتولّدُ منهما نحس: صحبةٌ ضارّة." : "", good(g) ? 0.3 : bad(g) ? -0.3 : 0, 185);
    add(`أصدقاؤك غالبًا: ${FRIENDS_IN_11[H(11).planet] || "—"}.`, 0, 186);
  } else if (topic === "enemy") {
    if (good(H(1)) && good(H(12))) add("لا أعداءَ تخشاهم.", 0.5, 186);
    else if (bad(H(1)) && good(H(12))) add("خصمُك أقوى الآن؛ تجنّبِ المواجهة.", -0.5, 186);
    else if (good(H(1)) && bad(H(12))) add("تظفرُ بأعدائك.", 0.5, 186);
    add(stab(H(12)) === "ثابت" ? "عداوتُهم ثابتة." : stab(H(12)) === "منقلب" ? "عداوتُهم لا تثبت." : "يعادونك مرّةً ويصالحونك أخرى.", 0, 186);
  } else if (topic === "prison") {
    if ([3, 9, 5].some((n) => same(12, n))) add(bad(H(10)) ? "يخرجُ بغير رضا صاحب الأمر." : good(H(10)) ? "يخرجُ برضا صاحب الأمر." : "يخرج.", 0.4, 186);
    if (good(H(12))) add("سعدٌ في الثاني عشر: خروجٌ بسلامة.", 0.4, 186);
    if (repeatsIn(12, [8])) add("الثاني عشر تكرّر في الثامن: خطرٌ شديد.", -0.6, 186);
    if (repeatsIn(12, [2])) add("الثاني عشر تكرّر في الثاني: يلقى شدّة.", -0.3, 186);
    const g = gen(1, 4);
    add(good(g) ? "عاقبةُ المحبوس إلى خير." : bad(g) ? "العاقبةُ صعبة." : "", good(g) ? 0.3 : bad(g) ? -0.3 : 0, 186);
  } else if (topic === "debt") {
    const g = gen2(gen(1, 7), gen(2, 8));
    add(good(g) ? "يُردُّ المال." : bad(g) ? "يتعوّقُ ردُّ المال." : "يُردُّ بعد تأخير.", good(g) ? 0.5 : bad(g) ? -0.5 : 0, 187);
  } else if (topic === "absent") {
    const watch = [9, 5, 3];
    if (watch.some((n) => same(n, 8))) add("علامةٌ ثقيلةٌ على الغائب (تكرارٌ في الثامن).", -0.6, 187);
    else if (watch.some((n) => same(n, 16) || same(n, 12))) add("الغائبُ في شدّةٍ أو خطر.", -0.4, 187);
    else add("يُرجى مجيئُه وسلامتُه.", 0.4, 187);
  } else if (topic === "love") {
    add(bad(H(1)) && bad(H(11)) ? "عاقبتُها الفسادُ والفضيحة." : good(H(1)) && good(H(11)) ? "عاقبتُها السترُ والصلاح." : "", good(H(1)) && good(H(11)) ? 0.5 : bad(H(1)) && bad(H(11)) ? -0.5 : 0, 187);
    if ((stab(H(1)) === "ثابت") !== (stab(H(11)) === "ثابت")) add("أحدُكما ثابتٌ والآخرُ متقلّب: لا بدّ من خلاف.", -0.2, 187);
    const g = gen(1, 11);
    add(good(g) ? "تتّفقان." : bad(g) ? "تختلفان." : "", good(g) ? 0.3 : bad(g) ? -0.3 : 0, 187);
  } else {
    // إخراجُ الضمير [ص ١٨٧]: من رؤوس (١، ٤، ٧، ١٥) شكلًا، ومن رؤوس (٣، ٥، ٩، ١٢) شكلًا، ومنهما شكلًا
    const heads = (ns) => byRows(ns.map((n) => H(n).rows[0]));
    const g = gen2(heads([1, 4, 7, 15]), heads([3, 5, 9, 12]));
    add(good(g) ? "ما في نفسِك أمرُ خير." : bad(g) ? "ما في نفسِك أمرٌ يقلقُك." : "ما في نفسِك أمرٌ متردّد.", good(g) ? 0.3 : bad(g) ? -0.3 : 0, 187);
  }
  // العمرُ وأطوارُه [ص ١٨٧]: الأوّلُ لأوّله والتاسعُ لوسطه والسابعُ لآخره
  if (topic === "general") add(`أطوارُ العمر: البداية ${good(H(1)) ? "طيّبة" : bad(H(1)) ? "متعبة" : "وسط"}، الوسط ${good(H(9)) ? "طيّب" : bad(H(9)) ? "متعب" : "وسط"}، الآخر ${good(H(7)) ? "طيّب" : bad(H(7)) ? "متعب" : "وسط"}.`, 0, 187);

  const details = out.filter((x) => x.text);
  const score = Math.max(-1, Math.min(1, details.reduce((a, x) => a + x.s, 0)));
  return { topic, details, score: Math.round(score * 100) / 100, src: SRC };
}

export default { judge, topicOf };

// ── جدولُ حروف السرّ [ص ٨] — قاعدةُ المتتالية المطبوعة ────────────────
// الصفُّ ١: ٥، ٦، ٨، ٩، ١١، ١٢، ١٤، ١٥، ١٧، ١٨، ٢٠، ٢١، ٢٣، ٢٤، ٢٦، ٢٧
//   = ٥ + (c + ⌊c/2⌋)   للأعمدة c = 0..15
// وكلُّ صفٍّ يزيد على سابقِه بمقدارِ ⌈١.٥⌉ تقريبًا (رُصِد: ٥،٦،٨،١٠،… للصفوف ١..).
export function tableSir(baqi, col) {
  const c = ((col % 16) + 16) % 16;
  const r = ((baqi - 1) % 9 + 9) % 9;
  const base = 5 + Math.round(1.5 * r);          // بدايةُ الصف
  return base + (c + Math.floor(c / 2));         // خطوةُ العمود ≈ ١.٥
}


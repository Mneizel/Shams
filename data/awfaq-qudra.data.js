// زوجُ الزوج: يُقسَم بنصفَين متساويين حتى ينتهي إلى الواحد (قوى ٢: ٢،٤،٨،١٦،٣٢،٦٤…).
// زوجُ الفرد: يُقسَم مرّةً واحدةً ثمّ لا ينتهي للواحد (٦،١٠،١٤،١٨،٢٢،٢٦…).
// زوجُ الزوج والفرد: يُقسَم أكثرَ من مرّةٍ ثمّ لا ينتهي للواحد (١٢،٢٠،٢٤،٢٨…).
// فردٌ: لا يقبل القسمةَ على ٢.
// العددُ الدائريّ: إذا ضُرِب في نفسه رجع آخرُه إلى ذاته (٥ و٦: ٥²=٢٥، ٦²=٣٦…).
export function classifyNumber(n) {
  n = Math.trunc(Math.abs(n));
  if (n < 1) return { n, class: "—", circular: false };
  const odd = n % 2 === 1;
  let m = n, halvings = 0;
  while (m % 2 === 0) { m /= 2; halvings++; }
  const cls = odd ? "فرد"
    : m === 1 ? "زوج الزوج"
    : halvings === 1 ? "زوج الفرد"
    : "زوج الزوج والفرد";
  const last = n % 10;
  const circular = (last === 5 || last === 6) || (n * n) % 10 === last;
  return { n, class: cls, halvings, circular };
}

// ── قبولُ الجبر (التطريف) بحسب المرتبة [ص ٢٢، ٤٨–٥٣] ────────────────
// المراتبُ الفرديّة (٣،٥،٧،٩…) وزوجُ الفرد (٦،١٠…) تقبل الجبر؛
// زوجُ الزوج (٤،٨…) له طريقةٌ خاصّة («مشي الفرزان» لا يقبل الجبر، والقطر يقبله).
export function acceptsJabr(order) {
  if (order < 3) return false;
  if (order % 2 === 1) return true;             // فرديّ
  if ((order / 2) % 2 === 1) return true;        // زوج الفرد (٦،١٠،١٤…)
  return "بطريقةٍ خاصّة";                          // زوج الزوج (٤،٨،١٢…)
}


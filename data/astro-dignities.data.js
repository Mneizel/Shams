// ── الوجوه (٣٦ وجهًا، كل ١٠°) — دور الكلدانيين ابتداءً من أوّل الحمل ──────
// المريخ، الشمس، الزهرة، عطارد، القمر، زحل، المشتري ... يتكرّر
const FACE_CYCLE = ["المريخ", "الشمس", "الزهرة", "عطارد", "القمر", "زحل", "المشتري"];
export function faceRuler(signIndex0, degInSign) {
  const faceIdx = signIndex0 * 3 + Math.floor(degInSign / 10); // 0..35
  return { faceNumberInSign: Math.floor(degInSign / 10) + 1, ruler: FACE_CYCLE[faceIdx % 7], faceIndex: faceIdx + 1 };
}

